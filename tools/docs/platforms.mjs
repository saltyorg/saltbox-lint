import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { targets } from "../../extension/scripts/release-inputs.mjs";

const document = new URL("../../docs/platforms.md", import.meta.url);

export function platformDocument(releaseTargets = targets) {
  const nativeCount = new Set(
    Object.values(releaseTargets).map(([os, arch]) => `${os}/${arch}`),
  ).size;
  const rows = Object.entries(releaseTargets).map(([target, [os, arch]]) => {
    const archive = `saltbox-lint_VERSION_${os}_${arch}.${os === "windows" ? "zip" : "tar.gz"}`;
    return `| ${target} | ${os}/${arch} | \`${archive}\` | \`saltbox-lint-VERSION-${target}.vsix\` |`;
  });
  return `# Supported platforms

<!-- Generated by tools/docs/platforms.mjs. Run make docs-update to refresh. -->

The packaging target map in [release-inputs.mjs](../extension/scripts/release-inputs.mjs)
is authoritative. ${rows.length} VSIX targets share ${nativeCount} standalone CLI targets. Replace
\`VERSION\` with the published version without its leading \`v\`, such as \`0.1.0\`.

| Extension host target | CLI target | Standalone archive | VSIX package |
| --- | --- | --- | --- |
${rows.join("\n")}

Choose the VSIX for the machine running the workspace extension host, which can
be a remote machine. The desktop's OS and architecture may differ. Alpine uses
the CGO-free Linux CLI for the same architecture. Its packaged binaries receive
musl probes; Alpine does not run the full installed editor host suite.

All ${nativeCount} native targets run source and packaged acceptance checks. Windows arm64
has no Go race runtime; the other native targets run race checks too.
Installed extension tests run at both configured editor versions on all native
targets. These describe required coverage, not evidence for a particular
release. Inspect that release commit's CI before claiming it passed.

See [CLI installation](../README.md#install),
[extension installation](../extension/README.md#platforms-and-installation), and
[release validation](extension-release.md).
`;
}

export function checkPlatforms(path = document, expected = platformDocument()) {
  if (readFileSync(path, "utf8") !== expected) {
    throw new Error("docs/platforms.md is stale; run make docs-update");
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (
    process.argv.length !== 3 ||
    !["--check", "--write"].includes(process.argv[2])
  ) {
    throw new Error("usage: node tools/docs/platforms.mjs --check|--write");
  }
  if (process.argv[2] === "--write")
    writeFileSync(document, platformDocument());
  else checkPlatforms();
}
